/**
 * Northstar Global Services: 100% fictional, deterministic USD demonstration dataset.
 * Every figure that depends on another (quote → opportunity → agreement → renewal → actuals) is computed with the
 * same finance engine the app uses, so totals reconcile. Output: demo-output/northstar.sql, loaded into a tenant of
 * kind 'demo' only. Names are generated from neutral word lists; no real company, person or Infoline record is used.
 *
 *   npx tsx scripts/generate-demo.ts [--tenant <uuid>] [--out demo-output/northstar.sql]
 */
