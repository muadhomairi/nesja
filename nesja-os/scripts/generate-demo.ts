function buildLines(term: number, scale: number): QuoteLineInput[] {
  const n = int(2, 4); const out: QuoteLineInput[] = [];
  const used = new Set<number>();
  for (let k = 0; k < n; k++) {
    let si = int(0, SERVICES.length - 1); while (used.has(si)) si = (si + 1) % SERVICES.length; used.add(si);
    const s = SERVICES[si]; const price = int(s.price[0], s.price[1]);
    const qty = s.m === "transactional" ? int(500, 4000) * scale : s.m === "one_time" ? 1 : int(2, 25) * scale;
    const costPct = s.costPct[0] + rnd() * (s.costPct[1] - s.costPct[0]);
    out.push({ description: s.d, pricingModel: s.m, quantity: qty, unitPrice: String(price), unitCost: fmt2(dec(price).times(costPct.toFixed(4))), discountRate: pick(["0", "0", "0.05", "0.10"]) });
  }
  return out;
}

