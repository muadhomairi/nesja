  using (exists (select 1 from public.quotes q where q.tenant_id = quote_lines.tenant_id and q.id = quote_lines.quote_id));
create policy quote_lines_write on public.quote_lines for all to authenticated
  using (exists (select 1 from public.quotes q where q.tenant_id = quote_lines.tenant_id and q.id = quote_lines.quote_id
                 and private.can(q.tenant_id, 'quote.edit', q.owner_id, q.business_unit_id)))
  with check (exists (select 1 from public.quotes q where q.tenant_id = quote_lines.tenant_id and q.id = quote_lines.quote_id
                 and private.can(q.tenant_id, 'quote.edit', q.owner_id, q.business_unit_id)));

create policy resource_roles_select on public.resource_roles for select to authenticated using (private.has_perm(tenant_id, 'costing.view'));
create policy resource_roles_write on public.resource_roles for all to authenticated
  using (private.has_perm(tenant_id, 'costing.manage')) with check (private.has_perm(tenant_id, 'costing.manage'));
create policy rate_cards_select on public.rate_cards for select to authenticated using (private.has_perm(tenant_id, 'quote.view'));
create policy rate_cards_write on public.rate_cards for all to authenticated
  using (private.has_perm(tenant_id, 'costing.manage')) with check (private.has_perm(tenant_id, 'costing.manage'));
create policy rate_card_items_select on public.rate_card_items for select to authenticated using (private.has_perm(tenant_id, 'quote.view'));
create policy rate_card_items_write on public.rate_card_items for all to authenticated
  using (private.has_perm(tenant_id, 'costing.manage')) with check (private.has_perm(tenant_id, 'costing.manage'));

create policy notifications_own on public.notifications for select to authenticated
  using (user_id = auth.uid() and private.is_member(tenant_id));
create policy notifications_mark_read on public.notifications for update to authenticated
  using (user_id = auth.uid() and private.is_member(tenant_id)) with check (user_id = auth.uid());

grant select on public.opportunity_stage_history, public.quote_totals to authenticated;
grant select, insert, update, delete on public.quote_lines, public.resource_roles, public.rate_cards, public.rate_card_items to authenticated;
grant select, update on public.notifications to authenticated;
