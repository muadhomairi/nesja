create or replace function private.record_stage_change() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' or new.stage is distinct from old.stage then
    insert into public.opportunity_stage_history(tenant_id, opportunity_id, from_stage, to_stage, changed_by)
    values (new.tenant_id, new.id, case when tg_op = 'UPDATE' then old.stage end, new.stage, auth.uid());
  end if;
  return new;
end $$;

