  unit_price numeric(18,4) not null check (unit_price >= 0),
  unit_cost numeric(18,4) not null default 0 check (unit_cost >= 0),
  discount_rate numeric(9,6) not null default 0 check (discount_rate >= 0 and discount_rate < 1),
  rate_card_item_id uuid,
  -- months the line is billed: 1 for one-time, the quote term for recurring/transactional (set by trigger)
  billing_months int not null default 1 check (billing_months between 1 and 120),
  line_revenue numeric(18,2) generated always as (round(quantity * unit_price * (1 - discount_rate) * billing_months, 2)) stored,
  line_cost numeric(18,2) generated always as (round(quantity * unit_cost * billing_months, 2)) stored,
  primary key (tenant_id, id),
  unique (tenant_id, quote_id, position),
  foreign key (tenant_id, quote_id) references public.quotes(tenant_id, id) on delete cascade,
  foreign key (tenant_id, rate_card_item_id) references public.rate_card_items(tenant_id, id)
);

create or replace function private.quote_line_months() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.pricing_model = 'one_time' then new.billing_months := 1;
  else select q.term_months into new.billing_months from public.quotes q where q.tenant_id = new.tenant_id and q.id = new.quote_id;
  end if;
  return new;
end $$;

-- Issued, accepted and superseded quotes are locked: a change needs a new revision.
create or replace function private.lock_issued_quote() returns trigger language plpgsql as $$
begin
  if old.status in ('issued', 'accepted', 'superseded') and (to_jsonb(new) - 'status' - 'updated_at') <> (to_jsonb(old) - 'status' - 'updated_at') then
    raise exception 'quote % rev % is %; create a new revision', old.number, old.revision, old.status using errcode = '42501';
  end if;
  return new;
end $$;

create or replace function private.lock_issued_lines() returns trigger language plpgsql security definer set search_path = '' as $$
declare v_status public.quote_status;
begin
  select q.status into v_status from public.quotes q where q.tenant_id = coalesce(new.tenant_id, old.tenant_id) and q.id = coalesce(new.quote_id, old.quote_id);
  if v_status in ('issued', 'accepted', 'superseded') then
    raise exception 'lines of an % quote cannot change', v_status using errcode = '42501';
  end if;
  return coalesce(new, old);
end $$;

-- Totals view: one deterministic definition used by UI, exports, approvals and reconciliation.
create view public.quote_totals with (security_invoker = true) as
select q.tenant_id, q.id as quote_id, q.number, q.revision, q.currency, q.term_months,
  coalesce(sum(l.line_revenue) filter (where l.pricing_model = 'one_time'), 0) as one_time_revenue,
  coalesce(sum(l.line_revenue) filter (where l.pricing_model = 'recurring'), 0) as recurring_revenue,
  coalesce(sum(l.line_revenue) filter (where l.pricing_model = 'transactional'), 0) as transactional_revenue,
  coalesce(sum(l.line_revenue), 0) as gross_revenue,
  round(coalesce(sum(l.line_revenue), 0) * q.overall_discount_rate, 2) as overall_discount,
  coalesce(sum(l.line_revenue), 0) - round(coalesce(sum(l.line_revenue), 0) * q.overall_discount_rate, 2) as tcv,
  coalesce(sum(l.line_cost), 0) + q.mobilisation_cost as total_cost,
  round(q.mobilisation_cost / q.term_months, 2) as mobilisation_per_month
from public.quotes q
left join public.quote_lines l on l.tenant_id = q.tenant_id and l.quote_id = q.id
group by q.tenant_id, q.id;

