-- Owned tables: RLS by permission + scope (own / business unit / all).
do $$
declare
  r record;
begin
  for r in select * from (values
      ('accounts', 'account'), ('contacts', 'account'), ('leads', 'lead'), ('opportunities', 'opportunity'),
      ('quotes', 'quote'), ('tenders', 'tender'), ('agreements', 'agreement'), ('renewals', 'renewal'),
      ('activities', 'activity'), ('approval_requests', 'approval'), ('documents', 'document'),
      ('financial_actuals', 'finance')) as t(tbl, module)
  loop
    execute format('alter table public.%I enable row level security', r.tbl);
    execute format($p$create policy %1$s_select on public.%1$I for select to authenticated
      using (private.can(tenant_id, '%2$s.view', owner_id, business_unit_id))$p$, r.tbl, r.module);
    execute format($p$create policy %1$s_insert on public.%1$I for insert to authenticated
      with check (private.has_perm(tenant_id, '%2$s.create'))$p$, r.tbl, r.module);
    execute format($p$create policy %1$s_update on public.%1$I for update to authenticated
      using (private.can(tenant_id, '%2$s.edit', owner_id, business_unit_id))
      with check (private.can(tenant_id, '%2$s.edit', owner_id, business_unit_id))$p$, r.tbl, r.module);
    execute format($p$create policy %1$s_delete on public.%1$I for delete to authenticated
      using (private.has_perm(tenant_id, '%2$s.delete'))$p$, r.tbl, r.module);
    execute format('create trigger %1$s_audit after insert or update or delete on public.%1$I for each row execute function private.audit_row()', r.tbl);
    if r.tbl not in ('approval_requests') then
      execute format('create trigger %1$s_touch before update on public.%1$I for each row execute function private.touch_updated()', r.tbl);
    end if;
    execute format('grant select, insert, update, delete on public.%I to authenticated', r.tbl);
  end loop;
end $$;
create trigger approval_requests_touch before update on public.approval_requests for each row execute function private.touch_updated();

